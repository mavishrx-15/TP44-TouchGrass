import type { Coordinates, DensityTier, MapBounds } from './discovery'

/**
 * The Iteration 3 planning contract (`backend/app/schemas/planning.py`,
 * owner Tian). Field names and shapes are kept identical to the backend's
 * Pydantic models - see the integration notes for the request/response
 * examples this mirrors.
 */

/** Mood is never sent; the backend rejects any field it doesn't list. */
export interface PlanningPreferences {
  canopy?: 'open' | 'mixed' | 'dense'
  shade?: 'sunny' | 'mixed' | 'cool'
  noise?: 'quiet' | 'lively'
  allergy?: 'avoid'
  walkingTime?: 5 | 10 | 15 | 20
}

export interface PlanningRequest {
  origin: Coordinates
  preferences: PlanningPreferences
}

export interface AreasRequest extends PlanningRequest {
  /** Zone ids to leave out, e.g. areas already visited today (device-only). */
  excludedZoneIds?: string[]
  limit?: number
}

export interface PlanningDestination {
  zoneId: string
  label: string
  center: Coordinates
  bounds: MapBounds
  density: DensityTier
  treeCount: number
}

export interface AreaOption {
  destination: PlanningDestination
  estimatedMinutes: number
  distanceMeters: number
}

export interface AreasResponse {
  areas: AreaOption[]
}

export interface PlanningRouteStep {
  instruction: string
  streetName: string | null
  start: Coordinates
  distanceMeters: number
}

export interface PlanningPreferenceMatch {
  key: 'canopy' | 'shade' | 'noise' | 'allergy' | 'time'
  matched: boolean
  detail: string
}

export interface PlannedRoute {
  origin: Coordinates
  destination: PlanningDestination
  durationMinutes: number
  distanceMeters: number
  encodedPolyline: string
  /** Share of the route through tree-dense zones, 0 to 1. */
  denseZoneShare: number
  summaryChips: string[]
  matches: PlanningPreferenceMatch[]
  /** Sprout's fixed-template explanation; never generated by a model. */
  explanation: string | null
  steps: PlanningRouteStep[]
  /** Set only when the route misses the chosen walking-time band. */
  message: string | null
}
